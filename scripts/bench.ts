// Runs the checker over every fixture and writes bench/results.json and
// bench/results.md. Run it with: npm run bench
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { checkPage, launchBrowser } from '../src/check.ts';
import { RULE_IDS } from '../src/rules.ts';
import { packageRoot } from '../src/skill/files.ts';
import { loadFixtures } from './fixtures.ts';
import { percent, score, type PageResult } from './score.ts';

const root = packageRoot();
const browser = await launchBrowser();
const version = browser.version();
const date = new Date().toISOString().slice(0, 10);
mkdirSync(join(root, 'bench'), { recursive: true });

/** Runs one folder of pages and writes bench/<name>.json and bench/<name>.md. */
async function measure(folder: string, name: string, title: string, intro: string): Promise<boolean> {
  const fixtures = loadFixtures(root, folder);
  const results: PageResult[] = [];
  let findings = 0;
  const started = Date.now();
  for (const fixture of fixtures) {
    const report = await checkPage(join(root, fixture.path), { browser, viewport: fixture.viewport });
    findings += report.findings.length;
    results.push({
      path: fixture.path,
      kind: fixture.kind,
      expect: fixture.expect,
      allow: fixture.allow,
      found: [...new Set(report.findings.map((f) => f.rule))],
    });
  }
  const elapsed = Date.now() - started;
  const scored = score(results);
  writeFileSync(
    join(root, 'bench', `${name}.json`),
    JSON.stringify({ date, chromium: version, elapsedMs: elapsed, findings, ...scored, results }, null, 2) + '\n',
  );
  const rows = RULE_IDS.map((rule) => {
    const s = scored.perRule[rule] ?? { tp: 0, fp: 0, fn: 0, precision: null, recall: null };
    return `| \`${rule}\` | ${s.tp} | ${s.fp} | ${s.fn} | ${percent(s.precision)} | ${percent(s.recall)} |`;
  });
  const { overall, pages } = scored;
  const md = [
    `# ${title}`,
    '',
    `Generated by \`npm run bench\` on ${date} with Chromium ${version}.`,
    '',
    intro,
    '',
    `${pages.bug + pages.fixed + pages.clean} pages: ${pages.bug} with a known bug, ${pages.fixed} fixed twins, ${pages.clean} clean. ${pages.passed} behaved as expected.`,
    '',
    '| Rule | True positives | False positives | False negatives | Precision | Recall |',
    '| --- | ---: | ---: | ---: | ---: | ---: |',
    ...rows,
    `| **All rules** | **${overall.tp}** | **${overall.fp}** | **${overall.fn}** | **${percent(overall.precision)}** | **${percent(overall.recall)}** |`,
    '',
    'One rule on one page counts once. Rules listed in a page as `rtl-check-allow` are real side effects of its bug and are not scored.',
    '',
    ...(scored.falsePositives.length
      ? ['False positives:', '', ...scored.falsePositives.map((f) => `- \`${f.path}\`: ${f.rule}`), '']
      : []),
    ...(scored.falseNegatives.length
      ? ['False negatives:', '', ...scored.falseNegatives.map((f) => `- \`${f.path}\`: ${f.rule}`), '']
      : []),
  ].join('\n');
  writeFileSync(join(root, 'bench', `${name}.md`), md);
  console.log(md);
  console.log(`${findings} findings in ${(elapsed / 1000).toFixed(1)} s\n`);
  return scored.falsePositives.length === 0 && scored.falseNegatives.length === 0;
}

try {
  const tuned = await measure(
    'fixtures',
    'results',
    'Fixture results',
    'These are the pages the checker was developed against, so read this as a regression test, not as accuracy on unseen code.',
  );
  await measure(
    'holdout',
    'holdout',
    'Held-out round 1, current code',
    'Round 1 was blind on its first run (see holdout-first-run.md). Its misses then drove fixes, so this rerun is no longer blind.',
  );
  await measure(
    'holdout-2',
    'holdout-2',
    'Held-out round 2, current code',
    'Round 2 was written after the round 1 fixes, against the frozen checker. See holdout-2-first-run.md for the blind run.',
  );
  if (!tuned) process.exitCode = 1;
} finally {
  await browser.close();
}
